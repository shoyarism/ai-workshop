#!/usr/bin/env python3
"""
Workshop Dynamic Tool Forge (Zero-Shot Capability Expansion)
============================================================
When an agent encounters an unknown API, undocumented endpoint, or novel protocol,
it enters a structured synthesis loop to generate a typed MCP server wrapper,
test it against the live target, and distill it into a permanent skill.
"""

import sys
import json
import subprocess
from pathlib import Path
from datetime import datetime, timezone

WORKSHOP_DIR = Path(__file__).resolve().parent.parent
SKILLS_DIR = WORKSHOP_DIR / "skills"
FORGE_DIR = WORKSHOP_DIR / ".workshop_state" / "tool_forge"
FORGE_DIR.mkdir(parents=True, exist_ok=True)

TEMPLATE_MCP_SERVER = '''#!/usr/bin/env python3
"""
Auto-generated MCP Server for {service_name}
Generated by Workshop Tool Forge on {timestamp}
Target: {target_url}
"""

import json
import sys
import asyncio
from typing import Any, Dict, List, Optional
from mcp.server import Server
from mcp.server.stdio import stdio_server
from mcp.types import Tool, TextContent
import httpx

server = Server("{service_name}")

# HTTP client with reasonable defaults
client = httpx.AsyncClient(timeout=30.0, follow_redirects=True)

@server.list_tools()
async def list_tools() -> List[Tool]:
    return [
        Tool(
            name="{tool_name}",
            description="{tool_description}",
            inputSchema={{
                "type": "object",
                "properties": {{
                    {input_schema}
                }},
                "required": {required_fields}
            }}
        )
    ]

@server.call_tool()
async def call_tool(name: str, arguments: Dict[str, Any]) -> List[TextContent]:
    if name == "{tool_name}":
        try:
            # Build request
            method = "{http_method}"
            url = "{target_url}"
            headers = {default_headers}
            params = {{}}
            json_data = {{}}
            
            # Map arguments to request
            {arg_mapping}
            
            # Execute
            response = await client.request(method, url, headers=headers, params=params, json=json_data)
            response.raise_for_status()
            result = response.json()
            
            return [TextContent(type="text", text=json.dumps(result, indent=2))]
        except Exception as e:
            return [TextContent(type="text", text=f"Error: {{str(e)}}")]
    raise ValueError(f"Unknown tool: {{name}}")

async def main():
    async with stdio_server() as (read_stream, write_stream):
        await server.run(read_stream, write_stream, server.create_initialization_options())

if __name__ == "__main__":
    asyncio.run(main())
'''

def analyze_target(target_spec: dict) -> dict:
    """Analyze a target API spec (OpenAPI, Swagger, or raw endpoint) and generate tool spec."""
    # This is a simplified analyzer - in production would parse OpenAPI/Swagger
    return {
        "service_name": target_spec.get("name", "unknown_api").lower().replace(" ", "_"),
        "tool_name": target_spec.get("tool_name", "call_api"),
        "tool_description": target_spec.get("description", "Auto-generated API call"),
        "target_url": target_spec.get("url", ""),
        "http_method": target_spec.get("method", "GET"),
        "default_headers": target_spec.get("headers", {"Content-Type": "application/json"}),
        "parameters": target_spec.get("parameters", {}),
        "required": target_spec.get("required", [])
    }

def generate_mcp_server(spec: dict) -> str:
    """Generate MCP server code from analyzed spec."""
    # Build input schema
    props = []
    required = []
    arg_mapping_lines = []
    
    for param_name, param_info in spec["parameters"].items():
        param_type = param_info.get("type", "string")
        param_desc = param_info.get("description", "")
        props.append(f'"{param_name}": {{"type": "{param_type}", "description": "{param_desc}"}}')
        if param_name in spec["required"]:
            required.append(param_name)
        
        # Map to request
        location = param_info.get("location", "query")
        if location == "query":
            arg_mapping_lines.append(f'params["{param_name}"] = arguments.get("{param_name}")')
        elif location == "body":
            arg_mapping_lines.append(f'json_data["{param_name}"] = arguments.get("{param_name}")')
        elif location == "header":
            arg_mapping_lines.append(f'headers["{param_name}"] = arguments.get("{param_name}")')
    
    input_schema = ",\n                    ".join(props)
    required_fields = json.dumps(required)
    arg_mapping = "\n            ".join(arg_mapping_lines)
    
    return TEMPLATE_MCP_SERVER.format(
        service_name=spec["service_name"],
        tool_name=spec["tool_name"],
        tool_description=spec["tool_description"],
        target_url=spec["target_url"],
        http_method=spec["http_method"],
        default_headers=json.dumps(spec["default_headers"]),
        input_schema=input_schema,
        required_fields=required_fields,
        arg_mapping=arg_mapping,
        timestamp=datetime.now(timezone.utc).isoformat()
    )

def test_generated_server(server_path: Path, test_args: dict) -> dict:
    """Test the generated MCP server with provided arguments."""
    try:
        # Write test script
        test_script = f'''
import asyncio
import sys
sys.path.insert(0, "{server_path.parent}")
from {server_path.stem} import call_tool

async def test():
    result = await call_tool("{test_args.get('tool_name', 'call_api')}", {json.dumps(test_args.get('arguments', {}))})
    print(result[0].text if result else "No result")

asyncio.run(test())
'''
        test_file = server_path.parent / f"test_{server_path.name}"
        test_file.write_text(test_script, encoding="utf-8")
        
        # Run test
        result = subprocess.run([sys.executable, str(test_file)], capture_output=True, text=True, timeout=30, cwd=str(server_path.parent))
        test_file.unlink(missing_ok=True)
        
        return {
            "success": result.returncode == 0,
            "stdout": result.stdout,
            "stderr": result.stderr
        }
    except Exception as e:
        return {"success": False, "error": str(e)}

def forge_tool(target_spec: dict, test_args: dict = None) -> dict:
    """Main forge pipeline: analyze -> generate -> test -> persist."""
    print(f"[FORGE] Analyzing target: {target_spec.get('name', 'unknown')}")
    
    # 1. Analyze
    spec = analyze_target(target_spec)
    
    # 2. Generate
    server_code = generate_mcp_server(spec)
    server_path = FORGE_DIR / f"{spec['service_name']}_mcp.py"
    server_path.write_text(server_code, encoding="utf-8")
    print(f"[FORGE] Generated MCP server: {server_path}")
    
    # 3. Test
    if test_args:
        print("[FORGE] Testing generated server...")
        test_result = test_generated_server(server_path, test_args)
        if not test_result["success"]:
            print(f"[FORGE] Test failed: {test_result.get('stderr', test_result.get('error'))}")
            return {"status": "failed", "spec": spec, "server_path": str(server_path), "test": test_result}
        print("[FORGE] Test passed")
    
    # 4. Distill into skill
    skill_dir = SKILLS_DIR / f"auto-{spec['service_name']}"
    skill_dir.mkdir(parents=True, exist_ok=True)
    
    skill_md = f'''---
name: "auto-{spec['service_name']}"
description: "Auto-generated MCP wrapper for {target_spec.get('name', 'unknown API')}"
category: "auto-generated"
tags: ["mcp", "auto-generated", "api-wrapper"]
version: "1.0.0"
generated: true
source_spec: {json.dumps(target_spec)}
---

# Auto-Generated Skill: {target_spec.get('name', 'Unknown API')}

This skill was automatically synthesized by the Workshop Tool Forge on {datetime.now(timezone.utc).isoformat()}.

## Target
- **Service**: {target_spec.get('name', 'Unknown')}
- **Endpoint**: {spec['target_url']}
- **Method**: {spec['http_method']}

## Generated MCP Server
Location: `{server_path.relative_to(WORKSHOP_DIR)}`

## Usage
```bash
# The MCP server can be run directly:
python {server_path.relative_to(WORKSHOP_DIR)}
```

## Parameters
{json.dumps(spec['parameters'], indent=2)}

## Test Status
{"✅ Tested and verified" if test_args and test_result.get("success") else "⚠️ Not tested"}
'''
    
    (skill_dir / "SKILL.md").write_text(skill_md, encoding="utf-8")
    print(f"[FORGE] Distilled into skill: {skill_dir}")
    
    return {
        "status": "success",
        "spec": spec,
        "server_path": str(server_path),
        "skill_path": str(skill_dir),
        "test": test_result if test_args else None
    }

if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Workshop Dynamic Tool Forge")
    parser.add_argument("--spec", required=True, help="Path to target spec JSON or inline JSON")
    parser.add_argument("--test-args", help="Path to test arguments JSON")
    parser.add_argument("--name", help="Service name override")
    args = parser.parse_args()
    
    # Parse spec
    spec_path = Path(args.spec)
    if spec_path.exists():
        target_spec = json.loads(spec_path.read_text(encoding="utf-8"))
    else:
        target_spec = json.loads(args.spec)
    
    if args.name:
        target_spec["name"] = args.name
    
    test_args = None
    if args.test_args:
        test_path = Path(args.test_args)
        if test_path.exists():
            test_args = json.loads(test_path.read_text(encoding="utf-8"))
        else:
            test_args = json.loads(args.test_args)
    
    result = forge_tool(target_spec, test_args)
    print(json.dumps(result, indent=2, default=str))